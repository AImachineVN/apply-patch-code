"""Auto-sync 10 profiles/*.md from patch_history.json.

Called after every successful apply (non-dry-run) to keep project progress
up-to-date for AI handoff. Appends or replaces an auto-generated section in
each profile file. User content above MARKER_START is preserved verbatim.
"""
from __future__ import annotations

import json
import logging
import re
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from . import __version__
from .profiles import PROFILES_DIR_NAME, PROFILES_TEMPLATE

log = logging.getLogger(__name__)

MARKER_START = "<!-- ===== AUTO-GENERATED BY APPLYPATCHCODE ===== -->"
MARKER_END = "<!-- ===== END AUTO SECTION ===== -->"

_CONFIG_DIR = ".apply_patch"
_HISTORY_FILENAME = "patch_history.json"

_ID_PATTERN = re.compile(r"(PATCH-[A-Z0-9-]+|TD-\d+|RISK-\d+|N-\d+|F-\d+)")


@dataclass
class SyncResult:
    files_updated: list[str] = field(default_factory=list)
    files_skipped: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)


def _read_history(project_root: Path) -> dict[str, Any]:
    path = project_root / _CONFIG_DIR / _HISTORY_FILENAME
    if not path.is_file():
        return {"entries": {}}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            return {"entries": {}}
        entries = data.get("entries", {})
        if not isinstance(entries, dict):
            return {"entries": {}}
        return data
    except (OSError, json.JSONDecodeError) as exc:
        log.warning("[PROFILES] Cannot read history: %s", exc)
        return {"entries": {}}


def _sorted_entries(history: dict[str, Any]) -> list[tuple[str, dict[str, Any]]]:
    entries = history.get("entries", {})
    if not isinstance(entries, dict):
        return []
    items = [(k, v) for k, v in entries.items() if isinstance(v, dict)]
    items.sort(key=lambda kv: kv[1].get("applied_at", ""))
    return items


def _extract_ids(text: str) -> set[str]:
    return set(_ID_PATTERN.findall(text))


def _split_sections(content: str) -> tuple[str, str]:
    """Return (goc_content, auto_content). auto_content = '' if no markers."""
    start = content.find(MARKER_START)
    if start == -1:
        return content.rstrip() + "\n", ""
    end = content.find(MARKER_END, start)
    if end == -1:
        return content.rstrip() + "\n", ""
    goc = content[:start].rstrip() + "\n"
    auto = content[start + len(MARKER_START):end].strip()
    return goc, auto


def _should_include(key: str, goc: str, seen: set[str]) -> bool:
    """Skip if key empty, already seen, or appears in user gốc content."""
    if not key or not key.strip():
        return False
    if key in seen:
        return False
    if key in goc:
        return False
    seen.add(key)
    return True


def _apply_markers(goc: str, auto: str, filename: str) -> str:
    timestamp = datetime.now(UTC).isoformat()
    block = (
        f"{MARKER_START}\n"
        f"<!-- Auto-generated. Do not edit below this line. -->\n"
        f"<!-- File: {filename} | Last update: {timestamp} | v{__version__} -->\n\n"
        f"{auto}\n\n"
        f"{MARKER_END}\n"
    )
    if goc.strip():
        return goc.rstrip() + "\n\n" + block
    return block


# ---------- Render functions ----------

def _render_patch_table(history: dict[str, Any], goc: str) -> str:
    lines = ["| Patch ID | Task | Applied At | Status |", "|---|---|---|---|"]
    seen: set[str] = set()
    added = False
    for _fname, entry in _sorted_entries(history):
        pid = str(entry.get("patch_id", "?")).strip()
        if not _should_include(pid, goc, seen):
            continue
        pr = entry.get("progress_report_snapshot") or {}
        task = str(pr.get("task_name", "(no task_name)")).strip()
        at = str(entry.get("applied_at", "?"))[:19]
        status = str(entry.get("status", "?"))
        if status == "undone":
            undone_at = str(entry.get("undone_at", ""))[:19]
            status = f"undone ({undone_at})"
        lines.append(f"| {pid} | {task} | {at} | {status} |")
        added = True
    if not added:
        lines.append("| _(none yet)_ | | | |")
    return "\n".join(lines)


def _render_00(history: dict[str, Any], goc: str) -> str:
    return "## Patch History (auto)\n\n" + _render_patch_table(history, goc)


