def _render_09(history: dict[str, Any], goc: str) -> str:
    lines = ["## AI Handoff Status (auto)", ""]
    entries = _sorted_entries(history)
    if not entries:
        lines.append("_(no patches applied yet)_")
        return "\n".join(lines)
    _fname, last = entries[-1]
    pid = str(last.get("patch_id", "?"))
    at = str(last.get("applied_at", "?"))[:19]
    last_status = str(last.get("status", "applied"))
    pr = last.get("progress_report_snapshot") or {}
    task = str(pr.get("task_name", "(no task_name)"))
    if last_status == "undone":
        undone_at = str(last.get("undone_at", ""))[:19]
        lines.append(f"### Last applied patch\n- **{pid}** - {task} (UNDONE at {undone_at})")
    else:
        lines.append(f"### Last applied patch\n- **{pid}** - {task}")
    lines.append(f"- Applied at: {at}")
    lines.append("")
    ctx = str(pr.get("mandatory_info_for_next_ai", "")).strip()
    if ctx:
        lines.append("### Critical context for next AI")
        lines.append("")
        lines.append(ctx)
        lines.append("")
    high_next = []
    for _f, entry in entries:
        pr2 = entry.get("progress_report_snapshot") or {}
        for nw in pr2.get("proposed_next_work", []) or []:
            pri = str(nw.get("priority", "")).strip().upper()
            if pri == "HIGH":
                high_next.append(str(nw.get("name", "")))
    if high_next:
        lines.append("### HIGH priority next work")
        lines.append("")
        for h in high_next:
            lines.append(f"- {h}")
    return "\n".join(lines)


