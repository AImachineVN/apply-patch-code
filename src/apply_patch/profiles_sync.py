def update_all_profiles(project_root: Path) -> SyncResult:
    """Rebuild auto section in all 10 profiles/*.md files.

    Best-effort: catches per-file errors into SyncResult.errors without raising.
    """
    result = SyncResult()
    profiles_dir = Path(project_root) / PROFILES_DIR_NAME
    try:
        profiles_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        result.errors.append(f"cannot create profiles dir: {exc}")
        return result

    history = _read_history(Path(project_root))

    for filename in PROFILES_TEMPLATE:
        path = profiles_dir / filename
        try:
            if path.is_file():
                current = path.read_text(encoding="utf-8")
            else:
                current = PROFILES_TEMPLATE.get(filename, f"# {filename}\n")
            goc, _old_auto = _split_sections(current)
            renderer = _RENDERERS.get(filename)
            if renderer is None:
                result.files_skipped.append(filename)
                continue
            auto_section = renderer(history, goc)
            new_content = _apply_markers(goc, auto_section, filename)
            path.write_text(new_content, encoding="utf-8")
            result.files_updated.append(filename)
        except OSError as exc:
            result.errors.append(f"{filename}: {exc}")
        except Exception as exc:  # noqa: BLE001
            result.errors.append(f"{filename}: {type(exc).__name__}: {exc}")

    return result
